#!/usr/bin/env node
/* vx/js/geom/geom-bake.mjs
   Regenerates vx/js/geom/geom-cad.js, the baked copy of the CAD measurements that
   geom.js exports synchronously (finDefaults, sectionPolygons, buildSection without a
   fetch). Run from anywhere, no arguments, after assembly.json or assembly.bin change:
     node vx/js/geom/geom-bake.mjs
   It reads the published assets with fs and measures them with the same code the page
   runs (geom-measure.js), so the baked numbers and the live numbers cannot drift
   apart silently: geometry.check in the browser compares the two. */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { measureAssembly, PROFILE_STEP_M } from './geom-measure.js';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const json = JSON.parse(fs.readFileSync(here('../../../assets/charger-explorer/assembly.json'), 'utf8'));
const bin = fs.readFileSync(here('../../../assets/charger-explorer/assembly.bin'));
const buffer = bin.buffer.slice(bin.byteOffset, bin.byteOffset + bin.byteLength);
if (buffer.byteLength !== json.bytes) throw new Error(`assembly.bin is ${buffer.byteLength} B, manifest says ${json.bytes} B`);

const { profile, fin, features } = measureAssembly(json, buffer);
const m7 = (x) => Number(x.toFixed(7));            // 0.1 um in metres
/* numbers to 0.1 um, recursively through arrays and plain objects; strings and ids kept */
const bakeValue = (v) => (typeof v === 'number' ? (Number.isInteger(v) ? v : m7(v))
  : Array.isArray(v) ? v.map(bakeValue)
  : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, bakeValue(x)]))
  : v);
const um = Array.from(profile.r, (r) => Math.round(r * 1e6)); // radius in whole micrometres

const data = {
  bytes: json.bytes,
  binScale: profile.binScale,
  step: PROFILE_STEP_M,
  length: m7(profile.length),
  noseTipY: m7(profile.noseTipY),
  tailY: m7(profile.tailY),
  profileParts: profile.parts,
  radiusUm: um,
  fin: {
    partId: fin.partId, root: m7(fin.root), tip: m7(fin.tip), span: m7(fin.span), sweep: m7(fin.sweep),
    thickness: m7(fin.thickness), rootLeadingEdgeFromNose: m7(fin.rootLeadingEdgeFromNose),
    rootRadius: m7(fin.rootRadius), tipTrailingEdgeAft: m7(fin.tipTrailingEdgeAft), area: Number(fin.area.toExponential(7)),
    hull: fin.hull.map(([s, h]) => [m7(s), m7(h)]),
  },
  features: Object.fromEntries(Object.entries(features).map(([k, v]) => [k, bakeValue(v)])),
};

const lines = [];
for (let i = 0; i < um.length; i += 16) lines.push('    ' + um.slice(i, i + 16).join(', ') + ',');
const out = `/* vx/js/geom/geom-cad.js
   GENERATED by geom-bake.mjs on ${new Date().toISOString().slice(0, 10)} from assets/charger-explorer/assembly.json +
   assembly.bin (${json.bytes} B). Do not edit by hand; rerun the bake.
   Tag: CAD. Lengths in metres; s is measured aft of the nose tip. radiusUm is the
   outer radius in micrometres every ${PROFILE_STEP_M * 1000} mm from the nose tip (index 0) to the aft face
   of the screw cap (last entry, at s = length). */
export const CAD = Object.freeze({
  bytes: ${data.bytes},
  binScale: ${data.binScale},
  step: ${data.step},
  length: ${data.length},
  noseTipY: ${data.noseTipY},
  tailY: ${data.tailY},
  profileParts: ${JSON.stringify(data.profileParts)},
  radiusUm: [
${lines.join('\n')}
  ],
  fin: ${JSON.stringify(data.fin)},
  features: ${JSON.stringify(data.features)},
});
`;
fs.writeFileSync(here('./geom-cad.js'), out);
console.log(`geom-cad.js: ${um.length} radius samples, length ${data.length} m, fin root ${data.fin.root} m, span ${data.fin.span} m`);
